"""Split a multi-subject TTL into one file per subject — an operator migration.

Two modes. **Re-filing** takes each record from the aggregate itself and must
preserve the graph exactly. **Importing** (`--from <config>`) takes each record
from another sandbox instead, which deliberately changes the graph — so instead
of asserting isomorphism it prints the per-record difference and asks.

The editors are FILE-based: a subject's triples are spread across files, so what
a person can coherently edit is one file, and a file describing several things
has no single record to edit. `record.read_instance`, the artist editor and the
profile editor all refuse a file with more than one named subject, and
`record.list_editable` skips them — which is correct for an aggregate and wrong
for a file that happens to hold several whole records.

`artists.ttl` is the case that matters: seven artists and artist profiles in one
file, so Edit artist and Edit artist profile cannot open any of them. Splitting
it is a RE-FILING, not a content change — the same triples, one subject each.

**Not everything multi-subject should be split**, and this script will not guess:

- `annotations.ttl` holds triples ABOUT records that live elsewhere (all 41 of
  its subjects have their own `<guid>.ttl`). Splitting it would put a second
  file under each subject's name. That is the fragment pattern the file-based
  editor was designed around, and it is fine as it is.
- `workOnSite_*.ttl` and `conceptQueue.ttl` are system output, regenerated by
  their workflows.
- `art.ttl`, `archivo.ttl` and `digitalRspates.ttl` hold 47 works that are
  grandfathered: they work in cwva-py and are never edited (Rick, 2026-09-27).

So the file to split is named on the command line, never discovered.

    python scripts/split_aggregate.py --file ttl/data/artists.ttl --dry-run
    python scripts/split_aggregate.py --file ttl/data/artists.ttl
    python scripts/split_aggregate.py --config config/production.rson \\
        --file ttl/data/artists.ttl

Importing is for the case re-filing cannot serve. Production's `artists.ttl`
holds four artist profiles and **none of them carries an `ops:template`**, so
re-filing them produces four records `read_profile` refuses — dead cards, no
entry forms. QA has the same four GUIDs with templates built through the form
builder, so the records are taken from there instead:

    python scripts/split_aggregate.py --config config/production.rson \\
        --file ttl/data/artists.ttl --from config/dashboard.rson --dry-run

A subject the source does not have falls back to the aggregate's own copy, and
that is reported rather than assumed.

It writes through `FileOps`, so nothing is hand-placed in the sandbox (law 12),
the original is trashed rather than deleted (CE_DESIGN §2.3, recoverable from
`.qa/trash`), and the result is left **uncommitted**: review it at Preview
Staged and distribute it through the ordinary gated exit. A re-filing shows
there as `files +N -1, ±triples +0/-0`, and any triple delta at all means
something went wrong.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

from rdflib import BNode, Graph, URIRef
from rdflib.compare import isomorphic

from rdflib.namespace import RDFS

from cwva_dashboard import config as cfgmod
from cwva_dashboard.promotion.drafts import graph_diff_lines
from cwva_dashboard.sandbox.fileops import FileOps
from cwva_dashboard.sandbox.paths import Sandbox

_CONFIG = Path(__file__).resolve().parents[1] / "config" / "dashboard.rson"


def subgraph(graph: Graph, subject) -> Graph:
    """One subject's triples, plus every blank node they reach.

    Blank nodes are followed because a quantity, a measurement system or a
    template field is part of the record that owns it and has no meaning apart
    from it. Named subjects are NOT followed: a reference to another record is a
    reference, and copying the other record in would duplicate it.
    """
    out, frontier, seen = Graph(), [subject], set()
    for prefix, namespace in graph.namespaces():
        out.bind(prefix, namespace)
    while frontier:
        node = frontier.pop()
        if node in seen:
            continue
        seen.add(node)
        for pred, obj in graph.predicate_objects(node):
            out.add((node, pred, obj))
            if isinstance(obj, BNode):
                frontier.append(obj)
    return out


def _source_records(config_path: str, directory: str, guids: list[str]) -> dict:
    """`{guid: Graph}` for the records another sandbox holds as `<guid>.ttl`."""
    cfg = cfgmod.load_config(config_path)
    ops = FileOps(Sandbox.open(cfgmod.sandbox_root(cfg, create=False), create=False))
    out = {}
    for guid in guids:
        try:
            text = ops.read_text(f"{directory}/{guid}.ttl")
        except Exception:
            continue
        graph = Graph()
        graph.parse(data=text, format="turtle")
        out[guid] = graph
    return out


def main(argv: list[str]) -> int:
    dry_run = "--dry-run" in argv
    config_path = str(_CONFIG)
    if "--config" in argv:
        config_path = argv[argv.index("--config") + 1]
    elif os.environ.get("CWVA_DASHBOARD_CONFIG"):
        config_path = os.environ["CWVA_DASHBOARD_CONFIG"]
    source_config = argv[argv.index("--from") + 1] if "--from" in argv else ""
    if "--file" not in argv:
        print("error: --file <sandbox-relative path> is required; this script "
              "never discovers what to split")
        return 2
    rel = argv[argv.index("--file") + 1].strip("/")

    cfg = cfgmod.load_config(config_path)
    qa_root = cfgmod.sandbox_root(cfg, create=False)
    ops = FileOps(Sandbox.open(qa_root, create=False))

    print(f"config : {config_path}")
    print(f"qa     : {qa_root}")
    print(f"file   : {rel}")

    whole = Graph()
    whole.parse(data=ops.read_text(rel), format="turtle")
    named = sorted({s for s in whole.subjects() if isinstance(s, URIRef)}, key=str)
    if len(named) < 2:
        print(f"\n{rel} has {len(named)} named subject(s); nothing to split.")
        return 0

    directory = str(Path(rel).parent)
    guids = [str(s).rstrip("/").rsplit("/", 1)[-1] for s in named]
    source = _source_records(source_config, directory, guids) if source_config else {}
    if source_config:
        print(f"source : {source_config} "
              f"({len(source)} of {len(guids)} records found there)")

    parts: list[tuple[str, Graph]] = []
    collisions: list[str] = []
    imported: list[str] = []
    for subject, guid in zip(named, guids):
        target = f"{directory}/{guid}.ttl"
        try:
            ops.read_text(target)
            collisions.append(target)
        except Exception:
            pass
        if guid in source:
            imported.append(guid)
            parts.append((target, source[guid]))
        else:
            parts.append((target, subgraph(whole, subject)))

    # THE CHECK THAT MAKES A RE-FILING SAFE: the union of the parts must be the
    # graph that went in. A subject left out, or a blank node reachable from two
    # subjects and therefore duplicated, shows up here rather than in the SOT.
    #
    # An IMPORT changes the graph on purpose, so isomorphism is the wrong
    # question there. The right one is "show me exactly what changes", which is
    # printed per record below and answered by a person.
    union = Graph()
    for _target, part in parts:
        for triple in part:
            union.add(triple)
    same = isomorphic(whole, union)
    print(f"\n{len(named)} subjects | {len(whole)} triples in | {len(union)} out "
          f"| graph preserved: {same}")
    for target, part in parts:
        origin = " (imported)" if Path(target).stem in imported else ""
        print(f"   {target:44} {len(part):4} triples{origin}")

    if source_config:
        total_add = total_rem = 0
        losses: list[str] = []
        for subject, (target, part) in zip(named, parts):
            added, removed = graph_diff_lines(
                subgraph(whole, subject), part,
                work_ns="http://visualartsdna.org/work/")
            total_add += len(added)
            total_rem += len(removed)
            label = str(whole.value(subject, RDFS.label) or subject)
            print(f"\n   --- {label}  +{len(added)} -{len(removed)}")
            for line in removed:
                print(f"       - {line}")
                losses.append(f"{label}: {line}")
            for line in added[:4]:
                print(f"       + {line}")
            if len(added) > 4:
                print(f"       + … {len(added) - 4} more")
        print(f"\nIMPORT would change the graph: +{total_add} -{total_rem} triples.")
        if losses:
            # Printed in full and never truncated: an addition you did not
            # expect is a surprise, a removal you did not expect is a loss.
            print(f"\n{len(losses)} statement(s) production has and the source "
                  "does NOT — these would be gone:")
            for line in losses:
                print(f"   - {line}")

    if collisions:
        print("\nREFUSED — these already exist, and overwriting one would "
              "destroy a record this script did not read:")
        for path in collisions:
            print(f"   {path}")
        return 1
    if not same and not source_config:
        missing = [t for t in whole if t not in union]
        print(f"\nREFUSED — the split would not preserve the graph "
              f"({len(missing)} triple(s) unaccounted for):")
        for triple in missing[:5]:
            print(f"   {triple}")
        return 1

    if dry_run:
        print("\nDRY RUN — nothing written.")
        return 0

    for target, part in parts:
        ops.write_text(target, part.serialize(format="turtle"), make_parents=True)
    trashed = ops.trash(rel)
    what = "imported" if source_config else "wrote"
    print(f"\n{what} {len(parts)} files; {rel} -> {trashed}")
    print("The QA tree is UNCOMMITTED. Review it at Preview Staged — a re-filing "
          "reads as files +N -1 with ±triples +0/-0 — and distribute it there.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
